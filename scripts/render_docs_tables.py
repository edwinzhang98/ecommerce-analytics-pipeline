"""Render the generated parts of the docs from the single sources of truth.

* docs/data_dictionary.md        <- dbt manifest + catalog (descriptions, types, tests, grain, materialization)
* docs/data_quality_report.md    <- the issue-register table between the BEGIN/END issue_register markers,
                                    from sql/data_quality/issue_register.yml with counts from the cache

Run after `make build docs cache` (the Makefile's `report` target calls it):
    uv run python scripts/render_docs_tables.py
"""
from __future__ import annotations

import json
import re
import sys
from collections import defaultdict
from pathlib import Path

import pandas as pd

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "src"))
from olist_analytics.config import load_settings  # noqa: E402

MARTS = ["fct_orders", "fct_order_items", "dim_customers", "dim_products", "dim_sellers", "dim_date",
         "customer_360", "seller_scorecard"]
UPDATE = {
    "fct_order_items": "Incremental (delete+insert on `order_item_key`): new orders since the last load minus a "
                       "3-day lookback, plus every order that was still open. See ADR 0005.",
}
DEFAULT_UPDATE = "Full rebuild on every `dbt build` (`make build`)."


def clean(text: str | None) -> str:
    text = " ".join((text or "").split())
    return text.replace("|", "\\|")


def column_tests(manifest: dict) -> dict:
    found: dict = defaultdict(list)
    for node in manifest["nodes"].values():
        if node["resource_type"] != "test":
            continue
        target = node.get("attached_node") or ""
        column = node.get("column_name")
        name = (node.get("test_metadata") or {}).get("name") or "singular"
        if target.startswith("model.olist_analytics.") and column:
            label = name if "known_issue" not in node.get("tags", []) else f"{name} (baseline)"
            found[(target.split(".")[-1], column)].append(label)
    return found


def model_tests(manifest: dict) -> dict:
    found: dict = defaultdict(list)
    for node in manifest["nodes"].values():
        if node["resource_type"] != "test" or node.get("column_name"):
            continue
        target = node.get("attached_node") or ""
        if target.startswith("model.olist_analytics."):
            found[target.split(".")[-1]].append(node["name"])
    return found


def render_data_dictionary(manifest: dict, catalog: dict, stats: dict) -> str:
    col_tests, mod_tests = column_tests(manifest), model_tests(manifest)
    rows = stats.get("mart_rows", {})
    out = [
        "# Data dictionary",
        "",
        "> Generated by `scripts/render_docs_tables.py` from the dbt manifest and catalog (the same source as",
        "> `dbt docs`). Do not edit by hand: change the model's YAML and re-run `make report`.",
        "",
        "Analysts query the **`marts`** schema only. Every mart has an enforced contract (column names and types",
        "cannot change silently) and `access: public`. Amounts are BRL; timestamps are local time",
        "(America/Sao_Paulo) unless the column name ends in `_utc`. Metric definitions:",
        "[02_metric_definitions.md](02_metric_definitions.md). How to use the tables: [analyst_guide.md](analyst_guide.md).",
        "",
        "| table | grain | rows | update | columns |",
        "|---|---|---:|---|---:|",
    ]
    nodes = {n["name"]: n for n in manifest["nodes"].values()
             if n["resource_type"] == "model" and n["package_name"] == "olist_analytics"}
    for name in MARTS:
        node = nodes[name]
        grain = (node["config"].get("meta") or {}).get("grain", "")
        out.append(f"| [`{name}`](#{name}) | {grain} | {rows.get(name, 0):,} | "
                   f"{'incremental' if name in UPDATE else 'full rebuild'} | {len(node['columns'])} |")
    for name in MARTS:
        node = nodes[name]
        cat_cols = catalog["nodes"].get(node["unique_id"], {}).get("columns", {})
        meta = node["config"].get("meta") or {}
        out += [
            "",
            f"## {name}",
            "",
            clean(node["description"]),
            "",
            f"- **Grain:** {meta.get('grain', '')}",
            f"- **Rows:** {rows.get(name, 0):,}",
            f"- **Update:** {UPDATE.get(name, DEFAULT_UPDATE)}",
            f"- **Built from:** {', '.join(sorted(p.split('.')[-1] for p in node['depends_on']['nodes']))}",
            f"- **Model-level tests:** {', '.join(sorted(mod_tests.get(name, []))) or 'none'}",
            f"- **Source:** [`dbt/{node['original_file_path']}`](../dbt/{node['original_file_path']})",
            "",
            "| column | type | description | tests |",
            "|---|---|---|---|",
        ]
        for col_name, col in node["columns"].items():
            dtype = col.get("data_type") or cat_cols.get(col_name, {}).get("type", "")
            tests = ", ".join(sorted(set(col_tests.get((name, col_name), []))))
            out.append(f"| `{col_name}` | {dtype.lower()} | {clean(col.get('description'))} | {tests} |")
    return "\n".join(out) + "\n"


def render_issue_register(issues: pd.DataFrame) -> str:
    lines = ["| ID | class | table | issue | affected | how it is handled | guarded by |", "|---|---|---|---|---:|---|---|"]
    for r in issues.itertuples():
        tests = ", ".join(f"`{t.strip()}`" for t in r.dbt_tests.split(",") if t.strip()) or "documented"
        lines.append(f"| {r.id} | {r._2} | `{r.table}` | {clean(r.title)} | {int(r.affected):,} {clean(r.unit)} | "
                     f"{clean(r.handling)} | {tests} |")
    return "\n".join(lines)


def main() -> int:
    settings = load_settings()
    artifacts = settings.artifacts_dir
    manifest = json.loads((artifacts / "manifest.json").read_text())
    catalog_path = artifacts / "catalog.json"
    catalog = json.loads(catalog_path.read_text()) if catalog_path.exists() else {"nodes": {}}
    stats = json.loads((settings.cache_dir / "project_stats.json").read_text())

    dictionary = REPO_ROOT / "docs" / "data_dictionary.md"
    dictionary.write_text(render_data_dictionary(manifest, catalog, stats), encoding="utf-8")
    print(f"wrote {dictionary.relative_to(REPO_ROOT)}")

    report = REPO_ROOT / "docs" / "data_quality_report.md"
    if report.exists():
        issues = pd.read_parquet(settings.cache_dir / "dq_issues.parquet")
        text = report.read_text(encoding="utf-8")
        pattern = re.compile(r"(<!-- BEGIN issue_register -->)(.*?)(<!-- END issue_register -->)", re.S)
        if pattern.search(text):
            text = pattern.sub(lambda m: f"{m.group(1)}\n{render_issue_register(issues)}\n{m.group(3)}", text)
            report.write_text(text, encoding="utf-8")
            print(f"filled the issue register in {report.relative_to(REPO_ROOT)}")
        else:
            print("no issue_register markers in data_quality_report.md; left unchanged")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
